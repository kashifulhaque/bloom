/// Renders [ReportData] as a PDF with the `pdf` package.
///
/// The PDF uses the built-in Helvetica font so it works offline. That font
/// covers Latin-1 only, so every string passes through [_s], which replaces
/// other characters (emoji, non-Latin scripts) with `?`.
library;

import 'dart:math' as math;
import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../core/dates.dart';
import 'report_data.dart';

const _pink = PdfColor.fromInt(0xFFE8457A);
const _pinkDeep = PdfColor.fromInt(0xFFB8235A);
const _period = PdfColor.fromInt(0xFFF0507A);
const _fertile = PdfColor.fromInt(0xFFB6E8E0);
const _teal = PdfColor.fromInt(0xFF138F80);
const _lavender = PdfColor.fromInt(0xFF9B87F5);
const _ink = PdfColor.fromInt(0xFF2A1F2D);
const _grey = PdfColor.fromInt(0xFF6E5F70);
const _line = PdfColor.fromInt(0xFFEBDFE4);
const _track = PdfColor.fromInt(0xFFF4EEF1);
const _zebra = PdfColor.fromInt(0xFFFBF7F9);

String _s(String v) => String.fromCharCodes(v.runes.map((r) => r <= 0xFF ? r : 0x3F));

String _cap(String s) => s.isEmpty ? s : s[0].toUpperCase() + s.substring(1);

Future<Uint8List> buildReportPdf(ReportData d, {PdfPageFormat format = PdfPageFormat.a4}) async {
  final doc = pw.Document(title: 'Bloom cycle report', author: 'Bloom');
  final theme = pw.ThemeData.withFont(
    base: pw.Font.helvetica(),
    bold: pw.Font.helveticaBold(),
  ).copyWith(defaultTextStyle: const pw.TextStyle(fontSize: 10, color: _ink, lineSpacing: 2));

  pw.Widget body(String t, {PdfColor? color}) =>
      pw.Text(_s(t), style: pw.TextStyle(fontSize: 10, color: color, lineSpacing: 2));

  doc.addPage(
    pw.MultiPage(
      pageFormat: format,
      theme: theme,
      margin: const pw.EdgeInsets.fromLTRB(40, 36, 40, 32),
      footer: (ctx) => pw.Container(
        margin: const pw.EdgeInsets.only(top: 16),
        padding: const pw.EdgeInsets.only(top: 6),
        decoration: const pw.BoxDecoration(
          border: pw.Border(top: pw.BorderSide(color: _line, width: 0.5)),
        ),
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              'Generated by Bloom on ${fmtFull(d.generated)}',
              style: const pw.TextStyle(fontSize: 8, color: _grey),
            ),
            pw.Text(
              'Page ${ctx.pageNumber} of ${ctx.pagesCount}',
              style: const pw.TextStyle(fontSize: 8, color: _grey),
            ),
          ],
        ),
      ),
      build: (ctx) => [
        _header(d),
        pw.SizedBox(height: 18),
        _heading('Summary'),
        pw.Row(
          children: [
            _stat('Average cycle', '${d.avgCycle}', 'days', _pink),
            pw.SizedBox(width: 10),
            _stat('Average period', '${d.avgPeriod}', 'days', _period),
            if (d.longestCycle > 0) ...[
              pw.SizedBox(width: 10),
              _stat('Shortest / longest cycle', '${d.shortestCycle} / ${d.longestCycle}', 'days', _lavender),
            ],
          ],
        ),
        pw.SizedBox(height: 10),
        _keyValue('Assessment', _cap(d.regularityText)),
        if (d.conditions.isNotEmpty) _keyValue('Reported conditions', d.conditions.join(', ')),
        if (d.contraception != null) _keyValue('Birth control', d.contraception!),
        _heading(d.cycles.isEmpty ? 'Cycles' : 'Last ${d.cycles.length} cycles'),
        if (d.cycles.isEmpty)
          body('No periods logged yet.', color: _grey)
        else ...[
          _cycleTable(d),
          pw.SizedBox(height: 14),
          _cycleBars(d),
        ],
        _heading('Most logged symptoms'),
        _counts(d.topSymptoms, 'No symptoms logged in this period.', _pink),
        _heading('Most logged moods'),
        _counts(d.topMoods, 'No moods logged in this period.', _lavender),
        if (d.bbtSummary != null || d.weightSummary != null) _heading('Measurements'),
        if (d.bbtSummary != null) _keyValue('Basal body temperature', d.bbtSummary!),
        if (d.weightSummary != null) _keyValue('Weight', d.weightSummary!),
        if (d.notes.isNotEmpty) ...[
          _heading('Notes'),
          for (final (date, note) in d.notes) _keyValue(fmtFull(date), note),
        ],
        pw.SizedBox(height: 20),
        pw.Container(
          padding: const pw.EdgeInsets.all(10),
          decoration: pw.BoxDecoration(
            color: _zebra,
            borderRadius: pw.BorderRadius.circular(6),
            border: pw.Border.all(color: _line, width: 0.5),
          ),
          child: body(
            'This report summarizes data the patient entered in Bloom, an open-source period tracker. '
            'Ovulation days and averages are estimates, not clinical measurements. It is not a diagnosis '
            'and is not medical advice.',
            color: _grey,
          ),
        ),
      ],
    ),
  );
  return doc.save();
}

pw.Widget _header(ReportData d) => pw.Container(
  padding: const pw.EdgeInsets.fromLTRB(18, 16, 18, 16),
  decoration: pw.BoxDecoration(
    gradient: const pw.LinearGradient(colors: [_pinkDeep, _pink]),
    borderRadius: pw.BorderRadius.circular(10),
  ),
  child: pw.Row(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: [
      pw.Expanded(
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              'BLOOM',
              style: pw.TextStyle(
                fontSize: 8,
                color: PdfColors.white,
                fontWeight: pw.FontWeight.bold,
                letterSpacing: 2,
              ),
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              'Menstrual cycle report',
              style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              'Period covered: ${fmtFull(d.from)} to ${fmtFull(d.generated)}',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.white),
            ),
          ],
        ),
      ),
      pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.end,
        children: [
          if (d.name.isNotEmpty)
            pw.Text(
              _s(d.name),
              style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
            ),
          if (d.age != null) pw.Text('Age ${d.age}', style: const pw.TextStyle(fontSize: 10, color: PdfColors.white)),
          pw.Text(_s('Goal: ${d.goal}'), style: const pw.TextStyle(fontSize: 10, color: PdfColors.white)),
        ],
      ),
    ],
  ),
);

pw.Widget _heading(String t) => pw.Container(
  width: double.infinity,
  margin: const pw.EdgeInsets.only(top: 18, bottom: 8),
  padding: const pw.EdgeInsets.only(bottom: 4),
  decoration: const pw.BoxDecoration(
    border: pw.Border(bottom: pw.BorderSide(color: _line, width: 0.75)),
  ),
  child: pw.Text(
    _s(t).toUpperCase(),
    style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: _pinkDeep, letterSpacing: 1.2),
  ),
);

pw.Widget _keyValue(String k, String v) => pw.Padding(
  padding: const pw.EdgeInsets.only(bottom: 4),
  child: pw.Row(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: [
      pw.SizedBox(
        width: 120,
        child: pw.Text(_s(k), style: const pw.TextStyle(fontSize: 9, color: _grey)),
      ),
      pw.Expanded(child: pw.Text(_s(v), style: const pw.TextStyle(fontSize: 10, lineSpacing: 2))),
    ],
  ),
);

pw.Widget _stat(String label, String value, String unit, PdfColor accent) => pw.Expanded(
  child: pw.Container(
    padding: const pw.EdgeInsets.fromLTRB(8, 8, 10, 8),
    decoration: pw.BoxDecoration(color: _zebra, borderRadius: pw.BorderRadius.circular(6)),
    child: pw.Row(
      children: [
        pw.Container(
          width: 3,
          height: 34,
          decoration: pw.BoxDecoration(color: accent, borderRadius: pw.BorderRadius.circular(1.5)),
        ),
        pw.SizedBox(width: 8),
        pw.Expanded(
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(label, style: const pw.TextStyle(fontSize: 8, color: _grey)),
              pw.SizedBox(height: 3),
              pw.RichText(
                text: pw.TextSpan(
                  children: [
                    pw.TextSpan(
                      text: value,
                      style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold),
                    ),
                    pw.TextSpan(
                      text: ' $unit',
                      style: const pw.TextStyle(fontSize: 9, color: _grey),
                    ),
                  ],
                ),
              ),
            ],
          ),
        ),
      ],
    ),
  ),
);

pw.Widget _cycleTable(ReportData d) => pw.TableHelper.fromTextArray(
  headers: ['Start', 'Cycle length', 'Period length', 'Est. ovulation'],
  data: [
    for (final c in d.cycles.reversed)
      [
        fmtFull(c.start),
        c.length != null ? '${c.length} days' : 'Current (day ${c.currentDay})',
        '${c.periodLength} days',
        'Cycle day ${c.ovulationDay}',
      ],
  ],
  headerStyle: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
  headerDecoration: const pw.BoxDecoration(
    color: _pink,
    borderRadius: pw.BorderRadius.vertical(top: pw.Radius.circular(6)),
  ),
  cellStyle: const pw.TextStyle(fontSize: 9.5),
  cellHeight: 22,
  cellPadding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 5),
  headerPadding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 6),
  oddRowDecoration: const pw.BoxDecoration(color: _zebra),
  border: const pw.TableBorder(bottom: pw.BorderSide(color: _line, width: 0.5)),
  cellAlignment: pw.Alignment.centerLeft,
  headerAlignment: pw.Alignment.centerLeft,
);

pw.Widget _counts(List<CountItem> items, String empty, PdfColor color) {
  if (items.isEmpty) return pw.Text(empty, style: const pw.TextStyle(fontSize: 10, color: _grey));
  final max = items.first.count;
  return pw.Column(
    children: [
      for (final i in items)
        pw.Padding(
          padding: const pw.EdgeInsets.only(bottom: 5),
          child: pw.Row(
            children: [
              pw.SizedBox(width: 120, child: pw.Text(_s(i.label), style: const pw.TextStyle(fontSize: 9.5))),
              pw.Expanded(
                child: pw.Stack(
                  children: [
                    pw.Container(
                      height: 8,
                      decoration: pw.BoxDecoration(color: _track, borderRadius: pw.BorderRadius.circular(4)),
                    ),
                    pw.Row(
                      children: [
                        pw.Expanded(
                          flex: math.max(1, (i.count * 100 / max).round()),
                          child: pw.Container(
                            height: 8,
                            decoration: pw.BoxDecoration(color: color, borderRadius: pw.BorderRadius.circular(4)),
                          ),
                        ),
                        pw.Expanded(flex: math.max(0, 100 - (i.count * 100 / max).round()) + 1, child: pw.SizedBox()),
                      ],
                    ),
                  ],
                ),
              ),
              pw.SizedBox(
                width: 50,
                child: pw.Text(
                  '${i.count} day${i.count == 1 ? '' : 's'}',
                  textAlign: pw.TextAlign.right,
                  style: const pw.TextStyle(fontSize: 9, color: _grey),
                ),
              ),
            ],
          ),
        ),
    ],
  );
}

/// One bar per cycle on a shared day scale: period, estimated fertile
/// window, and estimated ovulation, with week ticks underneath.
pw.Widget _cycleBars(ReportData d) {
  const scale = 45; // Days shown across the full width.
  const label = 64.0;
  const trail = 46.0;
  PdfColor dayColor(ReportCycle c, int day) {
    if (day <= c.periodLength) return _period;
    if (day == c.ovulationDay) return _teal;
    if (day >= c.ovulationDay - 5 && day <= c.ovulationDay + 1) return _fertile;
    return _track;
  }

  return pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: [
      for (final c in d.cycles.reversed)
        pw.Padding(
          padding: const pw.EdgeInsets.only(bottom: 5),
          child: pw.Row(
            children: [
              pw.SizedBox(
                width: label,
                child: pw.Text(fmtShort(c.start), style: const pw.TextStyle(fontSize: 8.5, color: _grey)),
              ),
              pw.Expanded(
                child: pw.Row(
                  children: [
                    for (var day = 1; day <= math.min(scale, c.length ?? c.currentDay ?? 1); day++)
                      pw.Expanded(
                        child: pw.Container(
                          height: 11,
                          margin: const pw.EdgeInsets.only(right: 0.8),
                          decoration: pw.BoxDecoration(
                            color: dayColor(c, day),
                            borderRadius: pw.BorderRadius.circular(1.5),
                          ),
                        ),
                      ),
                    for (var day = math.min(scale, c.length ?? c.currentDay ?? 1); day < scale; day++)
                      pw.Expanded(child: pw.SizedBox(height: 11)),
                  ],
                ),
              ),
              pw.SizedBox(
                width: trail,
                child: pw.Text(
                  c.length != null ? '${c.length} days' : 'day ${c.currentDay}',
                  textAlign: pw.TextAlign.right,
                  style: pw.TextStyle(
                    fontSize: 8.5,
                    fontWeight: pw.FontWeight.bold,
                    color: c.length == null ? _pinkDeep : _ink,
                  ),
                ),
              ),
            ],
          ),
        ),
      // Week ticks.
      pw.Row(
        children: [
          pw.SizedBox(width: label),
          pw.Expanded(
            child: pw.Row(
              children: [
                for (var day = 1; day <= scale; day++)
                  pw.Expanded(
                    child: day % 7 == 1 && day > 1
                        ? pw.Text('${day - 1}', style: const pw.TextStyle(fontSize: 6.5, color: _grey))
                        : pw.SizedBox(),
                  ),
              ],
            ),
          ),
          pw.SizedBox(width: trail),
        ],
      ),
      pw.SizedBox(height: 6),
      pw.Row(
        children: [
          pw.SizedBox(width: label),
          _legend(_period, 'Period'),
          _legend(_fertile, 'Fertile window (est.)'),
          _legend(_teal, 'Ovulation (est.)'),
          _legend(_track, 'Other days'),
        ],
      ),
    ],
  );
}

pw.Widget _legend(PdfColor c, String label) => pw.Padding(
  padding: const pw.EdgeInsets.only(right: 14, top: 2),
  child: pw.Row(
    children: [
      pw.Container(
        width: 9,
        height: 9,
        decoration: pw.BoxDecoration(color: c, borderRadius: pw.BorderRadius.circular(2)),
      ),
      pw.SizedBox(width: 4),
      pw.Text(label, style: const pw.TextStyle(fontSize: 8, color: _grey)),
    ],
  ),
);
